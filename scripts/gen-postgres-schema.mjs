// Derives prisma/postgres/schema.prisma from the MySQL schema (the single source of truth),
// so the app can also run on Postgres (Vercel/Neon). Run after changing prisma/schema.prisma:
//   node scripts/gen-postgres-schema.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const src = readFileSync("prisma/schema.prisma", "utf8");
const out = src
  .replace('provider = "mysql"', 'provider = "postgresql"')
  .replace('output   = "../src/generated/prisma"', 'output   = "../../src/generated/prisma"')
  .replaceAll("@db.DateTime(3)", "@db.Timestamp(3)");
if (out.includes('"mysql"')) throw new Error("schema still mentions mysql");
mkdirSync("prisma/postgres", { recursive: true });
writeFileSync("prisma/postgres/schema.prisma", "// GENERATED by scripts/gen-postgres-schema.mjs from prisma/schema.prisma — do not edit.\n" + out);
console.log("wrote prisma/postgres/schema.prisma");
